// Run: node tests/queue-processing.js
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname,'../assets/admin.js'),'utf8');
const moduleSource = source.slice(source.indexOf('// Process all queued pages'));
const requests = [], timers = [];
const button = {disabled:false,label:'',prop(key,value){this[key]=value;return this;},text(value){this.label=value;return this;}};
const cancel = {disabled:false,prop(key,value){this[key]=value;return this;},attr(){return 'cancel-nonce';},on(event,callback){this.click=callback;}};
const status = {message:'',text(value){this.message=value;return this;}};
const remaining = {value:0,text(value){this.value=value;}};
const form = {length:1,find(){return button;},serialize(){return 'action=wfebpg_process_queue_now&_wpnonce=test';},on(event,callback){this.submit=callback;}};
function $(selector){
    return {'#wfebpg-process-all-queue':form,'#wfebpg-process-all-status':status,'#wfebpg-queue-remaining':remaining,'#wfebpg-cancel-queue':cancel}[selector];
}
$.post = (url,data)=>{
    const request = {data,done(callback){this.success=callback;return this;},fail(callback){this.failure=callback;return this;},always(callback){this.finish=callback;return this;}};
    requests.push(request);
    return request;
};
const config = {ajaxUrl:'/admin-ajax.php'};
vm.runInNewContext(moduleSource,{jQuery:$,WFEBPG_Admin:config,window:{WFEBPG_Admin:config,
    setTimeout(callback,delay){const timer={callback,delay};timers.push(timer);return timer;},
    clearTimeout(timer){const index=timers.indexOf(timer);if(index!==-1)timers.splice(index,1);}}});
const submit = ()=>form.submit({preventDefault(){}});
const answer = data=>requests[requests.length-1].success({success:true,data});
submit();
submit();
assert.equal(requests.length,1,'Duplicate click started another worker');
assert.equal(button.disabled,true);
answer({processed:3,failed:1,remaining:4,busy:false});
assert.equal(remaining.value,4);
assert.equal(requests.length,1,'Request loop overlapped batches');
timers.shift().callback();
answer({processed:3,failed:0,remaining:1,busy:false});
timers.shift().callback();
answer({processed:1,failed:0,remaining:0,busy:false});
assert.match(status.message,/Handled 7 job\(s\); 1 failed/);
assert.equal(button.disabled,true);
assert.equal(timers.length,0,'Empty queue kept polling');
submit();
answer({processed:0,failed:0,remaining:0,busy:true});
assert.equal(timers[0].delay,1000,'Active worker was not retried');
assert.match(status.message,/Waiting/);
timers.shift().callback();
requests[requests.length-1].failure();
assert.equal(button.disabled,false,'Network failure prevented retry');
assert.match(status.message,/request failed/);
submit();
requests[requests.length-1].success({success:false,data:{message:'Unauthorized'}});
assert.equal(button.disabled,false);
assert.equal(status.message,'Unauthorized');
assert.equal(timers.length,0,'Failed request kept polling');
submit();
const inFlight = requests[requests.length-1];
cancel.click();
const cancellation = requests[requests.length-1];
assert.equal(cancellation.data.action,'wfebpg_cancel_queue');
assert.equal(cancellation.data.nonce,'cancel-nonce');
const requestCount = requests.length;
cancel.click();
assert.equal(requests.length,requestCount,'Duplicate cancellation was sent');
inFlight.success({success:true,data:{processed:3,remaining:4,failed:0,busy:false}});
assert.equal(timers.length,0,'Late worker response restarted a cancelled loop');
cancellation.success({success:true,data:{cancelled:4,remaining:0}});
cancellation.finish();
assert.match(status.message,/Cancelled 4 waiting/);
assert.equal(remaining.value,0);
assert.equal(button.disabled,true);
inFlight.failure();
assert.match(status.message,/Cancelled 4 waiting/,'Late failure replaced cancellation status');
submit();
answer({processed:1,failed:0,remaining:2,busy:false});
assert.equal(timers.length,1);
cancel.click();
assert.equal(timers.length,0,'Cancellation left a scheduled request');
const failedCancel = requests[requests.length-1];
failedCancel.failure();
failedCancel.finish();
assert.equal(button.disabled,false);
assert.equal(cancel.disabled,false);
assert.match(status.message,/could not be confirmed/);
console.log('Queue dashboard passed: batch drain, locks, retries, cancellation, cleared timers, and ignored late responses.');
